export function pickWelcomeMotivation(seed?: number): string {
  const list = WELCOME_MOTIVATIONS;
  if (!list.length) return "Гарного дня й вдалих угод.";
  if (typeof seed === "number" && Number.isFinite(seed)) {
    const idx = Math.abs(Math.trunc(seed)) % list.length;
    return list[idx]!;
  }
  return list[Math.floor(Math.random() * list.length)]!;
}
